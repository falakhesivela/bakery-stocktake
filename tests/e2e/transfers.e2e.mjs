// Bake → request → change & approve → pick (scan) → dispatch → delivery note
// → receive with a damaged cake → history; plus reject, standing orders,
// undo a bake, drafts and sign-out. Works on any data, not only the seed.
import { BASE, scan, seeInTable, seeText, walkthrough } from "./helpers.mjs"

export default function transfersWalkthrough() {
  return walkthrough("Production and transfers", async ({ as, log, problems }) => {
    const baker = await as("baker@bakery.test")
    await baker.goto(`${BASE}/production`)
    await baker.getByRole("combobox", { name: "Product" }).selectOption({ label: "Chocolate cake (large) (CAKE-CHOC-L)" })
    await baker.getByRole("spinbutton", { name: /How many/ }).fill("40")
    await baker.getByRole("button", { name: "Log bake" }).click()
    await seeText(baker, "Logged 40 Chocolate cake (large) as batch")
    const batchCode = (await baker.locator("span.font-mono").filter({ hasText: /^B\d{6}-/ }).first().textContent()).trim()
    await baker.getByRole("link", { name: "Print 40 labels" }).click()
    await baker.waitForURL(/\/labels\/print/)
    await seeText(baker, "40 labels")
    log(`Baker logged 40 chocolate cakes (${batchCode}) and opened 40 labels`)

    const westham = await as("westham@bakery.test")
    await westham.goto(`${BASE}/transfers/new?type=request`)
    await westham.getByRole("combobox", { name: "Item 1", exact: true }).selectOption({ label: "Chocolate cake (large) (CAKE-CHOC-L)" })
    await westham.getByRole("spinbutton", { name: "Quantity 1", exact: true }).fill("10")
    await westham.getByRole("button", { name: "Add line" }).click()
    await westham.getByRole("combobox", { name: "Item 2", exact: true }).selectOption({ label: "Vanilla cupcake (CUP-VAN)" })
    await westham.getByRole("spinbutton", { name: "Quantity 2", exact: true }).fill("6")
    await westham.getByRole("button", { name: "Send request" }).click()
    await westham.waitForURL(/\/transfers\/[0-9a-f-]{36}$/)
    await seeText(westham, "Waiting for approval")
    const code = (await westham.locator("h1:visible").first().textContent()).trim()
    await westham.getByRole("link", { name: "All transfers" }).click()
    await westham.getByRole("link", { name: "Request stock" }).click()
    await westham.waitForURL(/\/transfers\/new/)
    if ((await westham.getByRole("spinbutton", { name: "Quantity 1", exact: true }).inputValue()) !== "") {
      problems.push("request form was not fresh after sending")
    }
    log(`Westham requested ${code}; the request form starts fresh afterwards`)

    const warehouse = await as("warehouse@bakery.test")
    await warehouse.goto(`${BASE}/transfers/${code}`)
    await warehouse.getByRole("link", { name: "Change & approve" }).click()
    await seeText(warehouse, "Asked for 6")
    await warehouse.locator("div.grid").filter({ hasText: "Asked for 6" }).getByRole("spinbutton").fill("4")
    await warehouse.getByRole("button", { name: "Approve these quantities" }).click()
    await warehouse.waitForURL(/\/transfers\/[0-9a-f-]{36}$/)
    await seeText(warehouse, "Approved")
    log("Warehouse approved, with cupcakes changed from 6 to 4")

    await baker.goto(`${BASE}/transfers/${code}`)
    await baker.getByRole("button", { name: "Start picking" }).click()
    await baker.waitForURL(/\/pick$/)
    await seeText(baker, "10 of 10")
    await scan(baker, "Scan batch label", batchCode)
    await baker.waitForTimeout(500)
    await seeText(baker, "10 of 10")
    const scanned = baker.locator("div.grid").filter({ hasText: batchCode }).getByRole("spinbutton")
    if ((await scanned.inputValue()) !== "10") problems.push("scanned batch did not take the 10 cakes")
    await baker.getByRole("button", { name: "Dispatch", exact: true }).click()
    await baker.getByRole("button", { name: "Dispatch now" }).click()
    await baker.waitForURL(new RegExp(`/transfers/${code}$`))
    await seeText(baker, "On the way")
    await baker.getByRole("link", { name: "Delivery note" }).click()
    await seeText(baker, "Scan to receive")
    log("Baker picked (scanned batch swapped in), dispatched and printed the delivery note")

    const staff = await as("staff@bakery.test")
    await staff.goto(`${BASE}/transfers/${code}/receive`)
    const cakeInput = staff.getByRole("spinbutton", { name: "Chocolate cake (large) arrived" }).first()
    await cakeInput.fill(String(Number(await cakeInput.inputValue()) - 1))
    await staff.getByRole("combobox", { name: "Reason" }).selectOption("damaged")
    await staff.getByRole("textbox", { name: "Note" }).fill("Dropped at the door")
    await staff.getByRole("button", { name: "Confirm receipt" }).click()
    await staff.waitForURL(new RegExp(`/transfers/${code}$`))
    await seeText(staff, "Received with differences")
    await staff.goto(`${BASE}/stock/history?q=${batchCode}`)
    await seeInTable(staff, "Transfer difference")
    await seeInTable(staff, "Dropped at the door")
    log("Westham staff received it with one damaged cake; history shows the write-off")

    const riverside = await as("riverside@bakery.test")
    await riverside.goto(`${BASE}/transfers/new?type=request`)
    await riverside.getByRole("combobox", { name: "Item 1", exact: true }).selectOption({ label: "Carrot cake (large) (CAKE-CARROT-L)" })
    await riverside.getByRole("spinbutton", { name: "Quantity 1", exact: true }).fill("2")
    await riverside.getByRole("button", { name: "Send request" }).click()
    await riverside.waitForURL(/\/transfers\/[0-9a-f-]{36}$/)
    const rCode = (await riverside.locator("h1:visible").first().textContent()).trim()
    await warehouse.goto(`${BASE}/transfers/${rCode}`)
    await warehouse.getByRole("button", { name: "Reject" }).click()
    await warehouse.getByRole("dialog").getByLabel("Reason").fill("Oven broken today")
    await warehouse.getByRole("button", { name: "Reject request" }).click()
    await seeText(warehouse, "Oven broken today")
    log(`Riverside's request ${rCode} was rejected with a reason`)

    await westham.goto(`${BASE}/transfers/standing`)
    const sunday = westham.getByRole("spinbutton", { name: "Chocolate cake (large) on Sunday" })
    const next = (await sunday.inputValue()) === "2" ? "3" : "2"
    await sunday.fill(next)
    await westham.getByRole("button", { name: "Save standing order" }).click()
    await seeText(westham, "Saved 25 quantities")
    log("Westham changed its standing order")

    await baker.goto(`${BASE}/production`)
    await baker.getByRole("combobox", { name: "Product" }).selectOption({ label: "White loaf (BREAD-WHITE)" })
    await baker.getByRole("spinbutton", { name: /How many/ }).fill("7")
    await baker.getByRole("button", { name: "Log bake" }).click()
    await seeText(baker, "Logged 7 White loaf")
    const loafBatch = (await baker.locator("span.font-mono").filter({ hasText: /^B\d{6}-/ }).first().textContent()).trim()
    const loafRow = baker.locator("table tbody tr").filter({ hasText: loafBatch })
    await loafRow.getByRole("button", { name: /Undo/ }).click()
    await baker.getByRole("dialog").getByText(`batch ${loafBatch}`).waitFor()
    await baker.getByRole("dialog").getByLabel("Reason").fill("Typed 7 instead of 17")
    await baker.getByRole("button", { name: "Undo bake" }).click()
    await loafRow.getByText("Undone: Typed 7 instead of 17").waitFor()
    log(`Baker undid the mistaken bake ${loafBatch}`)

    await warehouse.goto(`${BASE}/transfers/new?type=send`)
    await warehouse.getByRole("combobox", { name: "Item 1", exact: true }).selectOption({ label: "Cake box (large) (BOX-CAKE-L)" })
    await warehouse.getByRole("spinbutton", { name: "Quantity 1", exact: true }).fill("20")
    await warehouse.getByRole("button", { name: "Save draft" }).click()
    await warehouse.waitForURL(/\/transfers\/[0-9a-f-]{36}$/)
    await warehouse.getByRole("button", { name: "Delete draft" }).click()
    await warehouse.getByRole("dialog").getByRole("button", { name: "Delete draft" }).click()
    await warehouse.waitForURL(/\/transfers$/)
    log("Warehouse saved and deleted a draft")

    await staff.getByRole("button", { name: /Thandi Staff/ }).click()
    await staff.getByRole("menuitem", { name: "Sign out" }).click()
    await staff.waitForURL(/\/login/)
    await staff.goto(`${BASE}/transfers`)
    await staff.waitForURL(/\/login/)
    log("Signing out returns to the login page")
  })
}
